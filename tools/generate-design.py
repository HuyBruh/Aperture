"""Generate Rust geometry from the reviewed, single-source collection spec."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = json.loads((ROOT / "design/collection.json").read_text(encoding="utf-8"))

def generate():
    lines = ["// @generated by tools/generate-design.py; edit design/collection.json.",
             "fn geometry(layout: Layout) -> Option<&'static [Widget]> {", "    match layout {"]
    for layout in SPEC["layouts"]:
        lines.append(f'        Layout::{layout["name"]} => Some(&[')
        for kind,x,y,w,h,mode in layout["widgets"]:
            lines.append(f'            Widget {{ kind: "{kind}", r: ({x}.0,{y}.0,{w}.0,{h}.0), mode: "{mode}" }},')
        lines.append('        ]),')
    lines += ["        _ => None,", "    }", "}", ""]
    return "\n".join(lines)

def rgb(h):
    return '(' + ', '.join(str(int(h[i:i+2],16)) for i in (0,2,4)) + ')'

def palettes():
    lines=['// @generated by tools/generate-design.py', 'const APERTURE_THEMES: &[Theme] = &[']
    for key,t in SPEC['palettes'].items():
        a=rgb(t['accent'])
        lines += ['    Theme {', f'        name: "{key}", bg: {rgb(t["bg"])}, panel: {rgb(t["panel"])}, text: {rgb(t["text"])}, muted: {rgb(t["muted"])}, dim: {rgb(t["dim"])},',
                  '        '+', '.join(f'{k}: [{a}, {a}]' for k in ['cpu','gpu','ram','ssd','net'])+f', up: {a}, fps: {a}, time: {rgb(t["text"])},', '    },']
    return '\n'.join(lines+ ['];',''])

def catalog():
    lines=['// @generated by tools/generate-design.py', 'const APERTURE_LAYOUTS: &[LayoutInfo] = &[']
    for l in SPEC['layouts']:
        lines.append('    LayoutInfo { '+', '.join(k+': '+json.dumps(l[k],ensure_ascii=False) for k in ['key','name','en','vi'])+', portrait: false },')
    lines+= ['];','const APERTURE_PALETTES: &[ThemeInfo] = &[']
    for key,t in SPEC['palettes'].items():
        lines.append(f'    ThemeInfo {{ key: "{key}", name: "{key.title()}", colors: [{rgb(t["accent"])}, {rgb(t["muted"])}, {rgb(t["panel"])}] }},')
    return '\n'.join(lines+['];',''])

def templates():
    lines=['// @generated by tools/generate-design.py', 'pub fn theme_template(key: &str) -> Vec<Widget> {', '    let text = match key {']
    for l in SPEC['layouts']:
        text=';'.join(f'group_{kind},{x},{y},{w},{h},24,1,f2f3ef,v1' for kind,x,y,w,h,mode in l['widgets'])
        lines.append('        '+json.dumps(l['key'])+' => '+json.dumps(text)+',')
    return '\n'.join(lines+['        _ => return Vec::new(),','    };','    parse(text).unwrap_or_default()','}',''])

if __name__ == '__main__':
    import sys
    for name,content in [('templates.rs',templates()),('geometry.rs',generate()),('palettes.rs',palettes()),('studio_catalog.rs',catalog())]:
        target=ROOT/'src/dashboard'/name
        if '--check' in sys.argv:
            assert target.read_text(encoding='utf-8') == content, f'{name} is stale'
        else:
            target.write_text(content,encoding='utf-8')
    print('Design geometry, palettes and catalog are current.')
